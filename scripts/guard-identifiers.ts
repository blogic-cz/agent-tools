export function identifierMatches(
  text: string,
  allowedHashes: ReadonlySet<string> = new Set(),
): Array<{ start: number; end: number }> {
  const masked = text
    .replace(/(?:@)?blogic-cz\/agent-tools\b/gi, (value) => " ".repeat(value.length))
    .replace(/\bGITHUB_TOKEN\b/g, (value) => " ".repeat(value.length));
  const found: Array<{ start: number; end: number }> = [];
  for (const match of masked.matchAll(/[A-Za-z0-9]+/g)) {
    const token = match[0].toLowerCase();
    const hashes = byLength.get(token.length);
    const hash = createHash("sha256").update(token).digest("hex");
    if (hashes?.has(hash) && !allowedHashes.has(hash))
      found.push({ start: match.index, end: match.index + token.length });
  }
  return found;
}
export function anonymizeIdentifiers(text: string): string {
  const matches = identifierMatches(text).toSorted((a, b) => a.start - b.start || b.end - a.end);
  let result = "",
    end = 0;
  for (const match of matches) {
    if (match.start < end) continue;
    result += text.slice(end, match.start) + "example";
    end = match.end;
  }
  return result + text.slice(end);
}
